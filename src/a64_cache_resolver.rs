/// A deliberately small production resolver service. It executes only exact,
/// independently audited capability selectors, never arbitrary exports.
/// No selector calls into Apple runtime state: all read commpage +0x23.
pub(super) struct AuditedResolvers {
    uuid: [u8; 16],
    trap: u64,
    stack_top: u64,
    executable_regions: Vec<(u64, u64)>,
    cached_targets: std::cell::RefCell<std::collections::HashMap<(u64, u64), u64>>,
    executions: std::cell::Cell<usize>,
}
impl AuditedResolvers {
    pub(super) fn new(
        cpu: &mut A64Cpu,
        plan: &super::cache::CachePlan,
        scratch: u64,
    ) -> Result<Self, String> {
        let mut service = Self::for_plan(plan)?;
        service.map_scratch(cpu, scratch)?;
        Ok(service)
    }
    pub(super) fn for_plan(plan: &super::cache::CachePlan) -> Result<Self, String> {
        let path = plan
            .files
            .first()
            .ok_or("resolver cache has no main file")?;
        let mut file = std::fs::File::open(path).map_err(|e| e.to_string())?;
        file.seek(std::io::SeekFrom::Start(0x58))
            .map_err(|e| e.to_string())?;
        let mut uuid = [0; 16];
        file.read_exact(&mut uuid).map_err(|e| e.to_string())?;
        if !matches!(uuid, IOS11_UUID | IOS16_UUID) {
            return Err("cache UUID has no audited capability resolvers".into());
        }
        let executable_regions = plan
            .regions
            .iter()
            .filter(|r| r.init_prot & 4 != 0)
            .map(|r| {
                r.vmaddr
                    .checked_add(r.size)
                    .map(|end| (r.vmaddr, end))
                    .ok_or("resolver cache region overflow")
            })
            .collect::<Result<Vec<_>, _>>()?;
        Ok(Self {
            uuid,
            trap: 0,
            stack_top: 0,
            executable_regions,
            cached_targets: std::cell::RefCell::new(std::collections::HashMap::new()),
            executions: std::cell::Cell::new(0),
        })
    }
    pub(super) fn map_scratch(&mut self, cpu: &mut A64Cpu, scratch: u64) -> Result<(), String> {
        if self.trap != 0 {
            return Err("resolver scratch already initialized".into());
        }
        if scratch == 0 || scratch & 0xfff != 0 {
            return Err("resolver scratch must be nonzero and page aligned".into());
        }
        let stack = scratch
            .checked_add(0x1000)
            .ok_or("resolver scratch overflow")?;
        let stack_top = scratch
            .checked_add(0x1ff0)
            .ok_or("resolver stack overflow")?;
        super::commpage::ensure_mapped(cpu)?;
        cpu.map_zeroed(scratch, 0x1000, 5)?;
        cpu.map_zeroed(stack, 0x1000, 3)?;
        cpu.try_write_bytes(scratch, &0xd4000fc1u32.to_le_bytes())?;
        self.trap = scratch;
        self.stack_top = stack_top;
        Ok(())
    }
    fn check_executable(&self, address: u64) -> Result<(), String> {
        if address & 3 != 0
            || !address.checked_add(4).is_some_and(|end| {
                self.executable_regions
                    .iter()
                    .any(|(start, limit)| address >= *start && end <= *limit)
            })
        {
            return Err("audited resolver address is outside executable cache memory".into());
        }
        Ok(())
    }
    pub(super) fn executions(&self) -> usize {
        self.executions.get()
    }
    pub(super) fn resolve(
        &self,
        cpu: &mut A64Cpu,
        stub: u64,
        resolver: u64,
    ) -> Result<u64, String> {
        if self.trap == 0 {
            return Err("resolver scratch is not initialized".into());
        }
        let (expected, target): (&[u8], u64) = match (self.uuid, stub, resolver) {
            (IOS11_UUID, 0x180b18c98, RESOLVER) => (&AUDITED_RESOLVER, TARGET),
            (IOS11_UUID, 0x180b18ca4, 0x180b13124) => (&IOS11_ADD32_BARRIER, 0x180b173cc),
            (IOS11_UUID, 0x180b18cf8, 0x180b162fc) => (&IOS11_CAS32, 0x180b175f4),
            (IOS11_UUID, 0x180b18cbc, 0x180b12658) => (&IOS11_ADD64_BARRIER, 0x180b1745c),
            (IOS11_UUID, 0x180b18d04, 0x180b130a0) => (&IOS11_CAS32_BARRIER, 0x180b1761c),
            (IOS11_UUID, 0x180b18d64, 0x180b130cc) => (&IOS11_CASPTR_BARRIER, 0x180b1766c),
            (IOS16_UUID, 0x18dba17cc, 0x18db916e0) => (&DISPATCH_RESOLVER, 0x18db355c0),
            (IOS16_UUID, 0x1d1ba4484, 0x1d1b9cd5c) => (&PTHREAD_MUTEX_INIT_RESOLVER, 0x1d1b9ecf8),
            (IOS16_UUID, 0x1d1ba4490, 0x1d1b9a6dc) => (&PTHREAD_MUTEX_LOCK_RESOLVER, 0x1d1b9fb6c),
            (IOS16_UUID, 0x1d1ba44a8, 0x1d1b99770) => (&PTHREAD_MUTEX_UNLOCK_RESOLVER, 0x1d1b9fa38),
            (IOS16_UUID, 0x1d1b055ec, 0x1d1affd38) => (&UNFAIR_LOCK_RESOLVER, 0x1d1b0301c),
            (IOS16_UUID, 0x1d1b0561c, 0x1d1b02aa8) => (&UNFAIR_UNLOCK_RESOLVER, 0x1d1b03094),
            (IOS16_UUID, 0x18dba2324, 0x18db928d8) => (&VOUCHER_ADOPT_RESOLVER, 0x18db54d50),
            (IOS16_UUID, 0x1d1b051fc, 0x1d1b02490) => (&ATOMIC_ADD32_BARRIER_RESOLVER, 0x1d1b038b0),
            (IOS16_UUID, 0x1d1ba4424, 0x1d1b9bef4) => {
                (&PTHREAD_COND_BROADCAST_RESOLVER, 0x1d1b9da88)
            }
            _ => {
                if self.uuid == IOS11_UUID {
                    let entry = IOS11_REQUIRED_SELECTORS.iter()
                        .find(|entry| entry.0 == stub && entry.1 == resolver)
                        .ok_or_else(|| format!("unaudited cache resolver {resolver:#x} (stub {stub:#x})"))?;
                    (&entry.2[..], entry.3)
                } else {
                let entry = (self.uuid == IOS16_UUID)
                    .then(|| {
                        TERRARIA_CAPABILITY_SELECTORS
                            .iter()
                            .chain(BATCH_CAPABILITY_SELECTORS.iter())
                            .find(|entry| entry.0 == stub && entry.1 == resolver)
                    })
                    .flatten()
                    .ok_or_else(|| {
                        format!("unaudited cache resolver {resolver:#x} (stub {stub:#x})")
                    })?;
                (&entry.2[..], entry.3)
                }
            }
        };
        self.check_executable(stub)?;
        self.check_executable(resolver)?;
        let mut actual = vec![0; expected.len()];
        cpu.read_guest_into(resolver, &mut actual)?;
        if actual != expected {
            return Err("audited capability resolver bytes differ".into());
        }
        // Every call verifies capabilities are still truthful and read-only.
        super::commpage::ensure_mapped(cpu)?;
        if let Some(address) = self.cached_targets.borrow().get(&(stub, resolver)) {
            return Ok(*address);
        }
        let result = call_at(cpu, resolver, &[], 10_000, self.trap, self.stack_top)?;
        self.check_executable(result)?;
        if result != target {
            return Err(format!(
                "audited capability resolver returned unexpected target {result:#x}"
            ));
        }
        self.cached_targets
            .borrow_mut()
            .insert((stub, resolver), result);
        self.executions.set(self.executions.get() + 1);
        Ok(result)
    }
}

fn call(cpu: &mut A64Cpu, entry: u64, args: &[u64], budget: u64) -> Result<u64, String> {
    call_at(cpu, entry, args, budget, TRAP, STACK + 0xff0)
}

fn call_at(
    cpu: &mut A64Cpu,
    entry: u64,
    args: &[u64],
    budget: u64,
    trap: u64,
    stack_top: u64,
) -> Result<u64, String> {
    let saved = cpu.save_context();
    let result = (|| {
        cpu.set_pc(entry);
        if args.len() > 8 {
            return Err("resolver argument count exceeds AArch64 register ABI".into());
        }
        cpu.set_sp(stack_top);
        cpu.set_reg(A64Cpu::LR, trap);
        for (index, value) in args.iter().enumerate() {
            cpu.set_reg(index, *value);
        }
        let mut ticks = budget.min(10_000);
        if ticks == 0 {
            return Err("resolver tick budget exhausted".into());
        }
        loop {
            match cpu.run_or_step(Some(&mut ticks)) {
                A64State::Svc(0x7e) if cpu.pc() == trap + 4 => return Ok(cpu.reg(0)),
                A64State::Normal if ticks != 0 => (),
                A64State::Normal => return Err("resolver tick budget exhausted".into()),
                state => {
                    return Err(format!(
                        "audited resolver stopped: {state:?} at {:#x}",
                        cpu.pc()
                    ))
                }
            }
        }
    })();
    cpu.restore_context(&saved);
    result
}

fn check_target(plan: &super::cache::CachePlan, address: u64) -> Result<(), String> {
    if address & 3 != 0
        || !plan.regions.iter().any(|r| {
            r.init_prot & 4 != 0
                && address >= r.vmaddr
                && address
                    .checked_add(4)
                    .is_some_and(|end| end <= r.vmaddr + r.size)
        })
    {
        return Err("resolver result is not mapped executable cache memory".into());
    }
    Ok(())
}

pub(super) fn test(path: &Path) -> Result<(), String> {
    let mut file = std::fs::File::open(path).map_err(|e| e.to_string())?;
    file.seek(std::io::SeekFrom::Start(0x58))
        .map_err(|e| e.to_string())?;
    let mut uuid = [0u8; 16];
    file.read_exact(&mut uuid).map_err(|e| e.to_string())?;
    if uuid == IOS16_UUID {
        let (plan, mut cpu) = cache_map::map(path)?;
        let service = AuditedResolvers::new(&mut cpu, &plan, TRAP)?;
        let target = service.resolve(&mut cpu, 0x18dba17cc, 0x18db916e0)?;
        echo!("[a64] audited iOS16 dispatch_once_f capability resolver returned {target:#x}; no target implementation, app initialization or main executed");
        return Ok(());
    }
    if uuid
        != [
            0x73, 0x36, 0xd7, 0x5f, 0x30, 0x14, 0x33, 0xe7, 0x84, 0x3f, 0xe1, 0xf3, 0x52, 0x2f,
            0xc5, 0x2f,
        ]
    {
        return Err("resolver diagnostic requires audited iOS11 cache UUID".into());
    }
    let (plan, mut cpu) = cache_map::map(path)?;
    let mut code = [0u8; 44];
    cpu.read_into(RESOLVER, &mut code)?;
    if code != AUDITED_RESOLVER {
        return Err("audited resolver bytes differ".into());
    }
    cpu.map_zeroed(TRAP, 0x1000, 5)?;
    cpu.map_zeroed(STACK, 0x2000, 3)?;
    cpu.write_bytes(TRAP, &0xd4000fc1u32.to_le_bytes()); // svc #0x7e
                                                         // Darwin ARM64 commpage v3, CPU capabilities chosen conservatively for
                                                         // the emulated guest: no ARMv8.1 LSE claim. This resolver reads only +0x23.
    super::commpage::map(&mut cpu)?;
    let target = call(&mut cpu, RESOLVER, &[], 10_000)?;
    check_target(&plan, target)?;
    if target != TARGET {
        return Err(format!(
            "audited resolver returned unexpected target {target:#x}"
        ));
    }
    let expected = [
        0x28, 0x7c, 0x5f, 0x88, 0x08, 0x01, 0x00, 0x0b, 0x28, 0x7c, 0x09, 0x88, 0xa9, 0xff, 0xff,
        0x35, 0xe0, 0x03, 0x08, 0xaa, 0xc0, 0x03, 0x5f, 0xd6,
    ];
    let mut implementation = [0u8; 24];
    cpu.read_into(target, &mut implementation)?;
    if implementation != expected {
        return Err("audited atomic implementation bytes differ".into());
    }
    // Check the genuine returned implementation itself, not an HLE alias.
    cpu.write_bytes(WORD, &21u32.to_le_bytes());
    let result = call(&mut cpu, target, &[21, WORD], 10_000)?;
    let mut word = [0u8; 4];
    cpu.read_into(WORD, &mut word)?;
    if result != 42 || u32::from_le_bytes(word) != 42 {
        return Err("genuine atomic implementation failed add test".into());
    }
    echo!("[a64] audited OSAtomicAdd32 resolver returned {target:#x}; genuine atomic add returned/stored42; no app initialization or main executed");
    Ok(())
}

